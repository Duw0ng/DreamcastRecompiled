#!/usr/bin/env python3
"""Rebuild tests/interp/interp_fixtures.inc (SH-4 images for tests_sh4_interp).

Needs an SH-4 GNU toolchain (Ubuntu/Debian: apt install gcc-sh4-linux-gnu).
The generated .inc is committed, so normal Windows/MSVC builds and CTest do not
need the cross compiler; rerun this script only after editing the fixtures.

    python tools/interp/build_interp_fixtures.py [--prefix sh4-linux-gnu-]
"""
import argparse
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tests" / "interp"
OUT = SRC / "interp_fixtures.inc"

CFLAGS = ["-O2", "-ml", "-m4", "-ffreestanding", "-fno-builtin", "-fno-pic", "-fno-pie",
          "-ffp-contract=off", "-fno-math-errno", "-fno-stack-protector"]

# The default GNU ld layout is used on purpose: libgcc's 64-bit division
# helpers are PIC and address their tables through the GOT, which a minimal
# hand-written linker script silently mis-laid out (wrong results, no error).


def run(cmd):
    subprocess.run(cmd, check=True)


def symbols(prefix, elf):
    out = subprocess.run([prefix + "nm", "-n", str(elf)], check=True, capture_output=True, text=True).stdout
    table = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3:
            table[parts[2]] = int(parts[0], 16)
    return table


def build_image(prefix, tmp, name, sources, base, entry, wanted):
    objs = []
    for src in sources:
        obj = tmp / (src.stem + ".o")
        if src.suffix == ".S":
            run([prefix + "gcc", "-ml", "-m4", "-c", str(src), "-o", str(obj)])
        else:
            run([prefix + "gcc", *CFLAGS, "-c", str(src), "-o", str(obj)])
        objs.append(str(obj))
    elf = tmp / (name + ".elf")
    run([prefix + "gcc", "-nostdlib", "-static", "-no-pie", "-Wl,--no-warn-rwx-segments", "-Wl,--build-id=none",
         f"-Wl,-Ttext={base:#x}", f"-Wl,-e,{entry}", "-Wl,-z,noexecstack", *objs, "-lgcc", "-o", str(elf)])
    binary = tmp / (name + ".bin")
    run([prefix + "objcopy", "-O", "binary", "-R", ".eh_frame", "-R", ".comment", str(elf), str(binary)])
    syms = symbols(prefix, elf)
    missing = [s for s in wanted if s not in syms]
    if missing:
        raise SystemExit(f"missing symbols in {name}: {missing}")
    return binary.read_bytes(), {s: syms[s] for s in wanted}


def emit_array(name, data):
    lines = [f"static const std::uint8_t {name}[] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prefix", default="sh4-linux-gnu-")
    ns = ap.parse_args()
    with tempfile.TemporaryDirectory() as d:
        tmp = pathlib.Path(d)
        corpus, corpus_syms = build_image(
            ns.prefix, tmp, "corpus", [SRC / "interp_corpus.c", SRC / "sh4_freestanding.c"],
            0x8C010000, "dc_test_main", ["dc_test_main", "dc_square", "dc_mix", "dc_apply"])
        probes, probe_syms = build_image(
            ns.prefix, tmp, "probes", [SRC / "interp_asm.S"], 0x8C040000, "probe_delay",
            ["probe_delay", "probe_gbr", "probe_mac", "probe_irq", "probe_sleep", "probe_trapa"])
    parts = [
        "// Generated by tools/interp/build_interp_fixtures.py - do not edit.",
        "// Sources: tests/interp/interp_corpus.c, sh4_freestanding.c, interp_asm.S",
        "#pragma once",
        "#include <cstdint>",
        "",
        "constexpr std::uint32_t kCorpusBase = 0x8C010000u;",
        emit_array("kCorpusImage", corpus),
    ]
    parts += [f"constexpr std::uint32_t kCorpus_{k} = 0x{v:08X}u;" for k, v in corpus_syms.items()]
    parts += ["", "constexpr std::uint32_t kProbeBase = 0x8C040000u;", emit_array("kProbeImage", probes)]
    parts += [f"constexpr std::uint32_t kProbe_{k} = 0x{v:08X}u;" for k, v in probe_syms.items()]
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT} (corpus {len(corpus)} bytes, probes {len(probes)} bytes)")


if __name__ == "__main__":
    sys.exit(main())
