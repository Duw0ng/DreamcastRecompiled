void reset_cdda_locked(GDROMPlugin& p, std::uint32_t current_fad) {
    p.cdda = {};
    p.cdda.current_fad = current_fad;
    gd_cdda_reset_audio_cursor(p, 0u);
    p.command_state.current_fad = current_fad;
}

void cdda_advance_one_sector_locked(GDROMPlugin& p) {
    auto& gd = p.cdda;
    if (!gd.cdda_playing || gd.cdda_paused) return;
    ++gd.cdda_sector_ticks;
    auto complete = [&]() {
        gd.cdda_playing = false;
        gd.cdda_paused = false;
        gd.cdda_terminated = true;
        ++gd.cdda_completions;
    };
    if (gd.current_fad >= gd.cdda_end) {
        if (gd.cdda_repeat == 0u) { complete(); p.command_state.current_fad = gd.current_fad; return; }
        if (gd.cdda_repeat != 15u) --gd.cdda_repeat;
        gd.current_fad = gd.cdda_start;
        p.command_state.current_fad = gd.current_fad;
        return;
    }
    ++gd.current_fad;
    if (gd.current_fad >= gd.cdda_end) {
        if (gd.cdda_repeat == 0u) complete();
        else {
            if (gd.cdda_repeat != 15u) --gd.cdda_repeat;
            gd.current_fad = gd.cdda_start;
        }
    }
    p.command_state.current_fad = gd.current_fad;
}

