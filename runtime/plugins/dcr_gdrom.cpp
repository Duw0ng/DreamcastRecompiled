const char* gd_cdda_order_name(const CDDAState& gd) {
    if (gd.cdda_audio_byte_order == 2u) return "be";
    if (gd.cdda_audio_byte_order == 1u) return gd.cdda_audio_order_defaulted ? "le?" : "le";
    return "?le"; // undecided sectors are conservatively decoded little-endian
}

std::int16_t gd_cdda_load_s16(const std::array<std::uint8_t, 2352>& sector, std::size_t i, bool big_endian) {
    const std::uint16_t u = big_endian
        ? (static_cast<std::uint16_t>(sector[i]) << 8u) | static_cast<std::uint16_t>(sector[i + 1u])
        : static_cast<std::uint16_t>(sector[i]) | (static_cast<std::uint16_t>(sector[i + 1u]) << 8u);
    return static_cast<std::int16_t>(u);
}

const char* gd_cdda_scramble_name(const CDDAState& gd) {
    if (gd.cdda_audio_scramble_mode == 2u) return "yb";
    if (gd.cdda_audio_scramble_mode == 1u) return gd.cdda_audio_scramble_defaulted ? "raw?" : "raw";
    return "?raw";
}

std::uint64_t gd_cdda_signal_delta(const std::array<std::uint8_t, 2352>& sector, bool big_endian) {
    std::int32_t prev_l = gd_cdda_load_s16(sector, 0u, big_endian);
    std::int32_t prev_r = gd_cdda_load_s16(sector, 2u, big_endian);
    std::uint64_t delta = 0u;
    auto absdiff = [](std::int32_t a, std::int32_t b) -> std::uint64_t {
        const std::int64_t d = static_cast<std::int64_t>(a) - static_cast<std::int64_t>(b);
        return static_cast<std::uint64_t>(d < 0 ? -d : d);
    };
    for (std::size_t frame = 1u; frame < 588u; ++frame) {
        const std::size_t off = frame * 4u;
        const std::int32_t l = gd_cdda_load_s16(sector, off + 0u, big_endian);
        const std::int32_t r = gd_cdda_load_s16(sector, off + 2u, big_endian);
        delta += absdiff(l, prev_l) + absdiff(r, prev_r);
        prev_l = l;
        prev_r = r;
    }
    return delta;
}

const std::array<std::uint8_t, 2340>& gd_yellowbook_scrambler() {
    // ECMA-130 / Yellow-Book L2 scrambler, polynomial x^15 + x + 1.
    // The sequence resets for every 2352-byte sector and applies to bytes
    // 12..2351. XOR is its own inverse, so the same table descrambles.
    static const std::array<std::uint8_t, 2340> table = [] {
        std::array<std::uint8_t, 2340> out{};
        std::uint16_t lfsr = 1u;
        for (auto& byte : out) {
            std::uint8_t v = 0u;
            for (unsigned bit = 0u; bit < 8u; ++bit) {
                v |= static_cast<std::uint8_t>((lfsr & 1u) << bit);
                const std::uint16_t feedback = static_cast<std::uint16_t>((lfsr ^ (lfsr >> 1u)) & 1u);
                lfsr = static_cast<std::uint16_t>((lfsr >> 1u) | (feedback << 14u));
            }
            byte = v;
        }
        return out;
    }();
    return table;
}

void gd_cdda_yellowbook_descramble(std::array<std::uint8_t, 2352>& sector) {
    const auto& table = gd_yellowbook_scrambler();
    for (std::size_t i = 0u; i < table.size(); ++i) sector[12u + i] ^= table[i];
}

bool gd_cdda_has_sync_prefix(const std::array<std::uint8_t, 2352>& sector) {
    if (sector[0] != 0x00u || sector[11] != 0x00u) return false;
    for (std::size_t i = 1u; i < 11u; ++i)
        if (sector[i] != 0xFFu) return false;
    return true;
}

void gd_cdda_store_s16(std::array<std::uint8_t, 2352>& sector, std::size_t i,
                       std::int16_t value, bool big_endian) {
    const auto u = static_cast<std::uint16_t>(value);
    if (big_endian) {
        sector[i] = static_cast<std::uint8_t>(u >> 8u);
        sector[i + 1u] = static_cast<std::uint8_t>(u);
    } else {
        sector[i] = static_cast<std::uint8_t>(u);
        sector[i + 1u] = static_cast<std::uint8_t>(u >> 8u);
    }
}

void gd_cdda_prepare_scramble(GDROMPlugin& p) {
    auto& gd = p.cdda;
    const auto previous_mode = gd.cdda_audio_scramble_mode;
    gd.cdda_audio_sector_sync_prefix = gd_cdda_has_sync_prefix(gd.cdda_audio_cache);

    const std::uint64_t raw_delta = std::min(gd_cdda_signal_delta(gd.cdda_audio_cache, false),
                                             gd_cdda_signal_delta(gd.cdda_audio_cache, true));
    auto yb = gd.cdda_audio_cache;
    gd_cdda_yellowbook_descramble(yb);
    const std::uint64_t yb_delta = std::min(gd_cdda_signal_delta(yb, false),
                                            gd_cdda_signal_delta(yb, true));
    gd.cdda_audio_scramble_raw_delta = raw_delta;
    gd.cdda_audio_scramble_yb_delta = yb_delta;
    ++gd.cdda_audio_scramble_analyzed;
    gd.cdda_audio_scramble_defaulted = false;

    // Decide independently for every sector. A 4x margin is intentionally
    // conservative; ambiguous music inherits the previous sector mode to avoid
    // chatter. This also handles DiscJuggler tracks that genuinely switch from
    // Yellow-Book storage to raw PCM at an internal sector boundary.
    std::uint32_t mode = 0u;
    if (raw_delta * 4u < yb_delta) mode = 1u;
    else if (yb_delta * 4u < raw_delta) mode = 2u;
    else {
        mode = previous_mode != 0u ? previous_mode : 1u;
        gd.cdda_audio_scramble_defaulted = true;
    }
    if (previous_mode != 0u && mode != previous_mode) {
        ++gd.cdda_audio_scramble_transitions;
        std::cout << "[GDROM] CDDA encoding transition T" << gd.cdda_audio_track_number
                  << " fad=" << gd.cdda_audio_cache_fad
                  << " " << (previous_mode == 2u ? "yb" : "raw")
                  << "->" << (mode == 2u ? "yb" : "raw")
                  << " raw-delta=" << raw_delta << " yb-delta=" << yb_delta << "\n";
    }
    gd.cdda_audio_scramble_mode = mode;
    if (mode == 2u) gd.cdda_audio_cache = yb;
}

