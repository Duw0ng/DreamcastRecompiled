bool read_bytes_locked(GDROMPlugin& p, std::uint32_t fad, std::uint32_t byte_offset,
                       std::uint32_t bytes, std::uint8_t* out, std::size_t out_size) {
    if (!p.ready || (!out && bytes) || out_size < bytes || byte_offset >= p.logical_sector_size) return false;
    if (!open_stream(p)) return false;
    std::uint32_t remaining = bytes;
    std::uint32_t cur_fad = fad;
    std::uint32_t cur_off = byte_offset;
    std::size_t out_off = 0u;
    std::uint64_t touched = 0u;
    while (remaining) {
        const auto* t = find_data_track(p, cur_fad);
        if (!t || t->user_size != p.logical_sector_size || t->user_offset + t->user_size > t->sector_size) return false;
        const std::uint64_t sector_index = std::uint64_t(cur_fad - t->start_fad);
        const std::uint64_t file_offset = t->file_base + sector_index * t->sector_size + t->user_offset + cur_off;
        const std::uint32_t chunk = std::min<std::uint32_t>(remaining, t->user_size - cur_off);
        p.stream.clear();
        p.stream.seekg(static_cast<std::streamoff>(file_offset), std::ios::beg);
        if (!p.stream) return false;
        p.stream.read(reinterpret_cast<char*>(out + out_off), static_cast<std::streamsize>(chunk));
        if (p.stream.gcount() != static_cast<std::streamsize>(chunk)) return false;
        out_off += chunk;
        remaining -= chunk;
        cur_off += chunk;
        ++touched;
        if (cur_off == t->user_size) { cur_off = 0u; ++cur_fad; }
    }
    ++p.bulk_reads;
    p.sector_reads += touched;
    p.bytes_read += bytes;
    if (p.trace) {
        std::ostringstream os; os << "READ fad=" << fad << " off=" << byte_offset << " bytes=" << bytes
                                  << " sectors=" << touched;
        trace_line(p, os.str());
    }
    return true;
}

bool read_bytes_impl(void* instance, std::uint32_t fad, std::uint32_t byte_offset,
                     std::uint32_t bytes, std::uint8_t* out, std::size_t out_size) {
    auto* p = static_cast<GDROMPlugin*>(instance);
    if (!p) return false;
    std::lock_guard<std::mutex> lock(p->mutex);
    return read_bytes_locked(*p, fad, byte_offset, bytes, out, out_size);
}

std::uint32_t track_word(const Track& t, std::uint32_t fad) {
    const std::uint32_t ctrl_adr = ((t.data() ? 4u : 0u) << 4u) | 1u;
    return (ctrl_adr << 24u) | (fad & 0x00FFFFFFu);
}

bool build_toc_impl(void* instance, std::uint32_t area, std::uint32_t* words, std::size_t word_count) {
    auto* p = static_cast<GDROMPlugin*>(instance);
    if (!p || !p->ready || !words || word_count < 102u) return false;
    std::lock_guard<std::mutex> lock(p->mutex);
    std::fill_n(words, 102u, 0xFFFFFFFFu);
    if (p->tracks.empty()) return true;
    const std::uint32_t min_session = p->sessions.empty() ? p->tracks.front().session : p->sessions.front().session;
    const std::uint32_t max_session = p->sessions.empty() ? min_session : p->sessions.back().session;
    const std::uint32_t wanted = min_session == max_session ? min_session : (area ? max_session : min_session);
    const Track* first = nullptr;
    const Track* last = nullptr;
    for (const auto& t : p->tracks) {
        if (t.session != wanted || t.number == 0u || t.number > 99u) continue;
        if (!first || t.number < first->number) first = &t;
        if (!last || t.number > last->number) last = &t;
        words[t.number - 1u] = track_word(t, t.start_fad);
    }
    if (first && last) {
        words[99] = track_word(*first, first->number << 16u);
        words[100] = track_word(*last, last->number << 16u);
        const std::uint32_t leadout_fad = last->end_fad == 0x00FFFFFFu ? last->end_fad : last->end_fad + 1u;
        Track leadout = *last; leadout.mode = 1u;
        words[101] = track_word(leadout, leadout_fad);
    }
    ++p->toc_builds;
    if (p->trace) {
        std::ostringstream os; os << "TOC area=" << area << " session=" << wanted
                                  << " first=" << (first ? first->number : 0u)
                                  << " last=" << (last ? last->number : 0u);
        trace_line(*p, os.str());
    }
    return true;
}


