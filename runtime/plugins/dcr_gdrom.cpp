std::uint32_t render_cdda_frames_impl(void* instance, std::int16_t* out,
                                      std::uint32_t frames, bool host_clock) {
    auto* p = static_cast<GDROMPlugin*>(instance);
    if (!p || !out || frames == 0u || !p->ready) return 0u;
    std::lock_guard<std::mutex> lock(p->mutex);
    auto& gd = p->cdda;
    if (!gd.cdda_playing || gd.cdda_paused) return 0u;
    std::uint32_t produced = 0u;
    while (produced < frames && gd.cdda_playing && !gd.cdda_paused) {
        if (gd.cdda_audio_fad == 0u) gd_cdda_reset_audio_cursor(*p, gd.current_fad);
        if (gd.cdda_audio_frame == 0u) {
            const std::uint32_t af = gd.cdda_audio_fad;
            const std::uint32_t df = gd.current_fad;
            const std::uint32_t delta = af > df ? af - df : df - af;
            const bool outside = af < gd.cdda_start ||
                (gd.cdda_end > gd.cdda_start && af >= gd.cdda_end);
            if (outside || (!host_clock && delta > 2u)) gd_cdda_reset_audio_cursor(*p, df);
        }
        if (!gd_cdda_load_sector(*p, gd.cdda_audio_fad)) break;
        const std::size_t off = static_cast<std::size_t>(gd.cdda_audio_frame) * 4u;
        const bool big_endian = gd.cdda_audio_byte_order == 2u;
        const std::int16_t l = gd_cdda_load_s16(gd.cdda_audio_cache, off + 0u, big_endian);
        const std::int16_t r = gd_cdda_load_s16(gd.cdda_audio_cache, off + 2u, big_endian);
        out[produced * 2u + 0u] = l;
        out[produced * 2u + 1u] = r;
        ++gd.cdda_audio_frames_mixed;
        if (l != 0 || r != 0) ++gd.cdda_audio_nonzero_frames;
        ++produced;
        if (++gd.cdda_audio_frame >= 588u) {
            gd.cdda_audio_frame = 0u;
            ++gd.cdda_audio_fad;
        }
    }
    return produced;
}

