bool begin_multi_impl(void* instance, std::uint32_t fad, std::uint32_t count) {
    auto* p = static_cast<GDROMPlugin*>(instance);
    if (!p || !p->ready) return false;
    std::lock_guard<std::mutex> lock(p->mutex);
    const std::uint64_t bytes64 = std::uint64_t(count) * p->logical_sector_size;
    if (bytes64 > 0xFFFFFFFFull) return false;
    auto& s = p->command_state;
    s.multi_fad = fad;
    s.multi_offset = 0u;
    s.multi_remaining = static_cast<std::uint32_t>(bytes64);
    s.multi_total = s.multi_remaining;
    s.result[2] = 0u;
    s.result[3] = s.multi_remaining ? 1u : 0u;
    s.status = s.multi_remaining ? kGdcContinue : kGdcComplete;
    ++p->multi_starts;
    if (p->trace) {
        std::ostringstream os; os << "MULTI begin fad=" << fad << " sectors=" << count << " bytes=" << s.multi_remaining;
        trace_line(*p, os.str());
    }
    return true;
}

bool multi_transfer_impl(void* instance, std::uint32_t dest, std::uint32_t bytes, bool dma) {
    auto* p = static_cast<GDROMPlugin*>(instance);
    if (!p || !p->ready) return false;
    std::lock_guard<std::mutex> lock(p->mutex);
    auto& s = p->command_state;
    if (s.status != kGdcContinue || bytes == 0u || bytes > s.multi_remaining) return false;
    std::vector<std::uint8_t> bulk(bytes);
    if (!read_bytes_locked(*p, s.multi_fad, s.multi_offset, bytes, bulk.data(), bulk.size())) return false;
    if (!write_guest_bulk(*p, dest, bulk.data(), bulk.size())) return false;
    const std::uint64_t total_offset = std::uint64_t(s.multi_offset) + bytes;
    s.multi_fad += static_cast<std::uint32_t>(total_offset / p->logical_sector_size);
    s.multi_offset = static_cast<std::uint32_t>(total_offset % p->logical_sector_size);
    s.multi_remaining -= bytes;
    s.current_fad = s.multi_fad;
    s.result[2] = s.multi_total - s.multi_remaining;
    s.result[3] = s.multi_remaining ? 1u : 0u;
    if (s.multi_remaining == 0u) s.status = kGdcComplete;
    ++p->multi_transfers;
    if (dma) {
        ++p->dma_transfers;
        if (p->host && p->host->raise_irq) {
            p->host->raise_irq(p->host->host_context, 0u, kAsicEventGdDmaBit);
            ++p->dma_irqs;
        }
    } else {
        ++p->pio_transfers;
    }
    if (p->trace) {
        std::ostringstream os; os << (dma ? "DMA" : "PIO") << " transfer dest=0x" << std::hex << std::uppercase << dest
                                  << std::dec << " bytes=" << bytes << " remaining=" << s.multi_remaining;
        trace_line(*p, os.str());
    }
    return true;
}

