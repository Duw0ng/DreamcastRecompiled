bool write_guest_bulk(GDROMPlugin& p, std::uint32_t dest, const std::uint8_t* data, std::size_t bytes) {
    if (bytes == 0u) return true;
    if (!data || !p.host) return false;
    // G1/GD DMA normally targets SH-4 main RAM. Use the direct memory-region
    // fast path only there; VRAM/AICA writes must go through host write8 so
    // their dirty/epoch side effects are preserved.
    const std::uint32_t physical = dest & 0x1FFFFFFFu;
    const bool main_ram = physical >= 0x0C000000u && physical < 0x0D000000u &&
                          bytes <= 0x0D000000u - physical;
    if (main_ram && p.host->get_memory_region) {
        DCRMemoryRegionV2 region{};
        if (p.host->get_memory_region(p.host->host_context, dest, bytes, &region) && region.data &&
            (region.flags & DCR_MEM_WRITE) != 0u && region.size >= bytes) {
            std::memcpy(region.data, data, bytes);
            return true;
        }
    }
    if (!p.host->write8) return false;
    for (std::size_t i = 0; i < bytes; ++i)
        p.host->write8(p.host->host_context, dest + static_cast<std::uint32_t>(i), data[i]);
    return true;
}

