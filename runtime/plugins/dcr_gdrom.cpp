bool play_tracks_impl(void* instance, std::uint32_t first_number,
                      std::uint32_t last_number, std::uint32_t repeat) {
    auto* p = static_cast<GDROMPlugin*>(instance);
    if (!p || !p->ready) return false;
    std::lock_guard<std::mutex> lock(p->mutex);
    const auto* first = find_track_by_number(*p, first_number);
    const auto* last = find_track_by_number(*p, last_number);
    if (!first || !last || first_number == 0u || last_number < first_number) return false;
    auto& gd = p->cdda;
    gd.cdda_playing = true;
    gd.cdda_paused = false;
    gd.cdda_terminated = false;
    gd.cdda_sector_mode = false;
    gd.cdda_start = first->start_fad;
    gd.cdda_end = last->end_fad == 0x00FFFFFFu ? last->end_fad : last->end_fad + 1u;
    gd.cdda_repeat = repeat & 0xFu;
    gd.current_fad = gd.cdda_start;
    gd_cdda_reset_audio_cursor(*p, gd.cdda_start);
    p->command_state.current_fad = gd.current_fad;
    ++p->cdda_play_commands;
    std::ostringstream os;
    os << "CDDA PLAY_TRACKS " << first_number << "->" << last_number
       << " fad=" << gd.cdda_start << "->" << gd.cdda_end
       << " repeat=" << gd.cdda_repeat
       << " raw=" << (gd.cdda_audio_available ? "yes" : "no");
    log_line(*p, os.str());
    return true;
}

