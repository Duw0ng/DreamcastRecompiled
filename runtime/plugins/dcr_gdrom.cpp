void build_sessions(GDROMPlugin& p) {
    p.sessions.clear();
    for (const auto& t : p.tracks) {
        auto it = std::find_if(p.sessions.begin(), p.sessions.end(), [&](const Session& s) { return s.session == t.session; });
        if (it == p.sessions.end()) {
            Session s{};
            s.session = t.session;
            s.first_track = t.number;
            s.last_track = t.number;
            s.start_fad = t.start_fad;
            s.end_fad = t.end_fad;
            p.sessions.push_back(s);
        } else {
            it->first_track = std::min(it->first_track, t.number);
            it->last_track = std::max(it->last_track, t.number);
            it->start_fad = std::min(it->start_fad, t.start_fad);
            it->end_fad = std::max(it->end_fad, t.end_fad);
        }
    }
    std::sort(p.sessions.begin(), p.sessions.end(), [](const Session& a, const Session& b) { return a.session < b.session; });
}

