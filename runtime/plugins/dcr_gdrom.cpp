void gd_cdda_repair_impulses(GDROMPlugin& p) {
    auto& gd = p.cdda;
    if (gd.cdda_audio_scramble_mode != 2u) return;

    // Captured source-only WAVs showed that the remaining Yellow-Book artefact
    // consists of sparse one-to-three-sample bursts rather than broad decode
    // failure. The former neighbour-pair test missed bursts whenever one of the
    // adjacent samples was also damaged or the real waveform had a steep slope.
    //
    // Use a robust five-sample temporal median per channel. A sample is changed
    // only when it differs from that local median by more than 2048. Four passes reproduce the cleanup chain validated against
    // the captured source-only WAV: the approved preview used exactly this
    // median-5 / 2048 / four-pass combination before continuous resampling.
    // RAW CDDA is never filtered.
    const bool big_endian = gd.cdda_audio_byte_order == 2u;
    constexpr std::uint32_t kImpulseError = 2048u;
    auto absdiff = [](std::int32_t a, std::int32_t b) -> std::uint32_t {
        const std::int64_t d = static_cast<std::int64_t>(a) - static_cast<std::int64_t>(b);
        return static_cast<std::uint32_t>(d < 0 ? -d : d);
    };

    for (unsigned pass = 0u; pass < 4u; ++pass) {
        const auto source = gd.cdda_audio_cache;
        std::uint64_t pass_repairs = 0u;
        for (std::size_t channel = 0u; channel < 2u; ++channel) {
            const std::size_t byte_in_frame = channel * 2u;
            for (std::size_t frame = 2u; frame + 2u < 588u; ++frame) {
                std::array<std::int32_t, 5> window{};
                for (std::size_t i = 0u; i < window.size(); ++i) {
                    const std::size_t sample_frame = frame + i - 2u;
                    window[i] = gd_cdda_load_s16(source,
                        sample_frame * 4u + byte_in_frame, big_endian);
                }
                std::sort(window.begin(), window.end());
                const std::int32_t median = window[2u];
                const std::size_t off_cur = frame * 4u + byte_in_frame;
                const std::int32_t cur = gd_cdda_load_s16(source, off_cur, big_endian);
                if (absdiff(cur, median) <= kImpulseError) continue;
                gd_cdda_store_s16(gd.cdda_audio_cache, off_cur,
                                  static_cast<std::int16_t>(median), big_endian);
                ++gd.cdda_audio_impulse_repairs;
                ++pass_repairs;
            }
        }
        if (pass_repairs == 0u) break;
    }
}
void gd_cdda_commit_sector_tail(GDROMPlugin& p) {
    auto& gd = p.cdda;
    const bool big_endian = gd.cdda_audio_byte_order == 2u;
    gd.cdda_audio_prev_l = gd_cdda_load_s16(gd.cdda_audio_cache, 2348u, big_endian);
    gd.cdda_audio_prev_r = gd_cdda_load_s16(gd.cdda_audio_cache, 2350u, big_endian);
    gd.cdda_audio_prev_sample_valid = true;
}

void gd_cdda_begin_audio_track(GDROMPlugin& p, const Track& track) {
    if (p.cdda.cdda_audio_track_number == track.number) return;
    p.cdda.cdda_audio_track_number = track.number;
    p.cdda.cdda_audio_scramble_mode = 0u;
    p.cdda.cdda_audio_scramble_analyzed = 0u;
    p.cdda.cdda_audio_scramble_raw_delta = 0u;
    p.cdda.cdda_audio_scramble_yb_delta = 0u;
    p.cdda.cdda_audio_scramble_defaulted = false;
    p.cdda.cdda_audio_sector_sync_prefix = false;
    p.cdda.cdda_audio_prev_sample_valid = false;
    p.cdda.cdda_audio_byte_order = 0u;
    p.cdda.cdda_audio_order_analyzed = 0u;
    p.cdda.cdda_audio_order_le_delta = 0u;
    p.cdda.cdda_audio_order_be_delta = 0u;
    p.cdda.cdda_audio_order_defaulted = false;
    std::cout << "[GDROM] CDDA source T" << track.number
              << " S" << track.session
              << " fad=" << track.start_fad << "->" << track.end_fad
              << " raw=" << track.sector_size << "B\n";
}

void gd_cdda_analyze_audio_sector(GDROMPlugin& p) {
    if (p.cdda.cdda_audio_byte_order != 0u) return;
    std::uint64_t le_delta = 0u, be_delta = 0u;
    std::int32_t prev_le_l = gd_cdda_load_s16(p.cdda.cdda_audio_cache, 0u, false);
    std::int32_t prev_le_r = gd_cdda_load_s16(p.cdda.cdda_audio_cache, 2u, false);
    std::int32_t prev_be_l = gd_cdda_load_s16(p.cdda.cdda_audio_cache, 0u, true);
    std::int32_t prev_be_r = gd_cdda_load_s16(p.cdda.cdda_audio_cache, 2u, true);
    auto absdiff = [](std::int32_t a, std::int32_t b) -> std::uint64_t {
        const std::int64_t d = static_cast<std::int64_t>(a) - static_cast<std::int64_t>(b);
        return static_cast<std::uint64_t>(d < 0 ? -d : d);
    };
    for (std::size_t frame = 1u; frame < 588u; ++frame) {
        const std::size_t off = frame * 4u;
        const std::int32_t le_l = gd_cdda_load_s16(p.cdda.cdda_audio_cache, off + 0u, false);
        const std::int32_t le_r = gd_cdda_load_s16(p.cdda.cdda_audio_cache, off + 2u, false);
        const std::int32_t be_l = gd_cdda_load_s16(p.cdda.cdda_audio_cache, off + 0u, true);
        const std::int32_t be_r = gd_cdda_load_s16(p.cdda.cdda_audio_cache, off + 2u, true);
        le_delta += absdiff(le_l, prev_le_l) + absdiff(le_r, prev_le_r);
        be_delta += absdiff(be_l, prev_be_l) + absdiff(be_r, prev_be_r);
        prev_le_l = le_l; prev_le_r = le_r;
        prev_be_l = be_l; prev_be_r = be_r;
    }

    // Pure silence gives no useful byte-order evidence. Keep waiting instead
    // of consuming the analysis budget before a track's first audible sector.
    if (le_delta + be_delta < 4096u) return;
    p.cdda.cdda_audio_order_le_delta += le_delta;
    p.cdda.cdda_audio_order_be_delta += be_delta;
    ++p.cdda.cdda_audio_order_analyzed;
    const auto le = p.cdda.cdda_audio_order_le_delta;
    const auto be = p.cdda.cdda_audio_order_be_delta;

    // Correctly decoded music is generally much smoother sample-to-sample than
    // a byte-swapped interpretation. Require a 20% margin so ordinary noisy or
    // high-frequency material cannot flip the standard DiscJuggler LE default.
    if (le * 5u < be * 4u) p.cdda.cdda_audio_byte_order = 1u;
    else if (be * 5u < le * 4u) p.cdda.cdda_audio_byte_order = 2u;
    else if (p.cdda.cdda_audio_order_analyzed >= 16u) {
        p.cdda.cdda_audio_byte_order = 1u;
        p.cdda.cdda_audio_order_defaulted = true;
    }

    if (p.cdda.cdda_audio_byte_order != 0u) {
        std::cout << "[GDROM] CDDA byte-order T" << p.cdda.cdda_audio_track_number
                  << " -> " << gd_cdda_order_name(p.cdda)
                  << " le-delta=" << le << " be-delta=" << be
                  << " sectors=" << p.cdda.cdda_audio_order_analyzed << "\n";
    }
}

bool gd_cdda_load_sector(GDROMPlugin& p, std::uint32_t fad) {
    if (p.cdda.cdda_audio_cache_valid && p.cdda.cdda_audio_cache_fad == fad) return true;
    p.cdda.cdda_audio_cache_valid = false;
    p.cdda.cdda_audio_cache_fad = fad;

    const auto* track = find_audio_track_by_fad(p, fad);
    if (!track) {
        ++p.cdda.cdda_audio_track_misses;
        p.cdda.cdda_audio_available = false;
        return false;
    }
    gd_cdda_begin_audio_track(p, *track);
    // A raw Red-Book sector contains exactly 588 stereo frames = 2352 bytes.
    // DCR_DISC_MAP_V2 preserves the complete physical payload for mode=0 tracks.
    if (track->sector_size < 2352u || track->user_size < 2352u ||
        track->user_offset + 2352u > track->sector_size) {
        ++p.cdda.cdda_audio_read_failures;
        p.cdda.cdda_audio_available = false;
        return false;
    }
    if (!p.stream.is_open()) {
        p.stream.clear();
        p.stream.open(p.image_path, std::ios::binary);
    }
    if (!p.stream) {
        ++p.cdda.cdda_audio_read_failures;
        return false;
    }

    const std::uint64_t sector_index = static_cast<std::uint64_t>(fad - track->start_fad);
    const std::uint64_t file_offset = track->file_base + sector_index * track->sector_size + track->user_offset;
    p.stream.clear();
    p.stream.seekg(static_cast<std::streamoff>(file_offset), std::ios::beg);
    if (!p.stream) {
        ++p.cdda.cdda_audio_read_failures;
        return false;
    }
    p.stream.read(reinterpret_cast<char*>(p.cdda.cdda_audio_cache.data()), 2352);
    if (p.stream.gcount() != 2352) {
        ++p.cdda.cdda_audio_read_failures;
        return false;
    }
    p.cdda.cdda_audio_cache_valid = true;
    p.cdda.cdda_audio_available = true;
    ++p.cdda.cdda_audio_sector_reads;
    gd_cdda_prepare_scramble(p);
    gd_cdda_analyze_audio_sector(p);
    if (p.cdda.cdda_audio_scramble_mode == 2u && p.cdda.cdda_audio_sector_sync_prefix)
        gd_cdda_repair_sync_prefix(p);
    else
        gd_cdda_repair_impulses(p);
    gd_cdda_commit_sector_tail(p);
    return true;
}


void fill_track(const Track& in, DCRGDROMTrackV1* out) {
    if (!out) return;
    *out = {sizeof(DCRGDROMTrackV1), in.session, in.number, in.mode, in.start_fad, in.end_fad,
            in.file_base, in.sector_size, in.user_offset, in.user_size};
}

